create table if not exists public.product_categories (
  id uuid primary key default gen_random_uuid(),
  slug text unique not null,
  name_cn text not null default '',
  name_en text not null default '',
  name_gr text not null default '',
  image_url text not null default '',
  sort_order integer not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists product_categories_sort_order_idx on public.product_categories (sort_order);
drop trigger if exists categories_updated_at on public.product_categories;
create trigger categories_updated_at before update on public.product_categories
for each row execute function public.set_updated_at();

create table if not exists public.product_subcategories (
  id uuid primary key default gen_random_uuid(),
  category_id uuid not null references public.product_categories(id) on delete cascade,
  slug text not null,
  name_cn text not null default '',
  name_en text not null default '',
  name_gr text not null default '',
  sort_order integer not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (category_id, slug)
);

create index if not exists product_subcategories_category_id_idx on public.product_subcategories (category_id);
create index if not exists product_subcategories_sort_order_idx on public.product_subcategories (sort_order);
drop trigger if exists subcategories_updated_at on public.product_subcategories;
create trigger subcategories_updated_at before update on public.product_subcategories
for each row execute function public.set_updated_at();

alter table public.products enable row level security;
alter table public.business_settings enable row level security;
alter table public.product_categories enable row level security;
alter table public.product_subcategories enable row level security;

revoke all on table public.products, public.business_settings, public.product_categories, public.product_subcategories from anon, authenticated;
grant select on table public.products, public.business_settings, public.product_categories, public.product_subcategories to anon, authenticated;
grant select, insert, update, delete on table public.products, public.business_settings, public.product_categories, public.product_subcategories to service_role;
grant usage, select on sequence public.products_id_seq to service_role;

drop policy if exists "Public read active products" on public.products;
create policy "Public read active products" on public.products for select to anon, authenticated
using (is_active = true);

drop policy if exists "Public read business settings" on public.business_settings;
create policy "Public read business settings" on public.business_settings for select to anon, authenticated
using (true);

drop policy if exists "Public read active categories" on public.product_categories;
create policy "Public read active categories" on public.product_categories for select to anon, authenticated
using (is_active = true);

drop policy if exists "Public read active subcategories" on public.product_subcategories;
create policy "Public read active subcategories" on public.product_subcategories for select to anon, authenticated
using (is_active = true);

