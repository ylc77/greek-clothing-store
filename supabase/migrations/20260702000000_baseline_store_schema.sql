begin;

create extension if not exists pgcrypto;

create or replace function public.set_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  sku text unique not null,
  name_cn text not null default '',
  name_gr text not null default '',
  name_en text not null default '',
  description_cn text not null default '',
  description_gr text not null default '',
  description_en text not null default '',
  category text not null,
  subcategory text not null default '',
  price numeric(10,2) not null check (price >= 0),
  stock integer not null default 0 check (stock >= 0),
  sizes text not null default '',
  size_stock jsonb not null default '{}'::jsonb check (jsonb_typeof(size_stock) = 'object'),
  image_url text not null default '',
  image_urls jsonb not null default '[]'::jsonb check (jsonb_typeof(image_urls) = 'array'),
  image_width integer,
  image_height integer,
  brand text not null default '',
  barcode text not null default '',
  ean text not null default '',
  vat numeric(5,2) not null default 24,
  color text not null default '',
  additional_image_urls text not null default '',
  skroutz_url text not null default '',
  material text not null default '',
  fit text not null default '',
  season text not null default '',
  mpn text not null default '',
  availability text not null default '',
  size_chart jsonb not null default '{}'::jsonb check (jsonb_typeof(size_chart) = 'object'),
  fit_type text not null default 'regular',
  style_tags text[] not null default '{}',
  ai_keywords text[] not null default '{}',
  material_verified boolean not null default false,
  category_path_en text not null default '',
  category_path_gr text not null default '',
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists products_sku_idx on public.products (sku);
create index if not exists products_created_at_idx on public.products (created_at desc);
create index if not exists products_category_idx on public.products (category);
create index if not exists products_category_subcategory_idx on public.products (category, subcategory);
create index if not exists products_is_active_idx on public.products (is_active);

drop trigger if exists products_updated_at on public.products;
create trigger products_updated_at before update on public.products
for each row execute function public.set_updated_at();

create table if not exists public.business_settings (
  id uuid primary key default gen_random_uuid(),
  business_name text not null default 'Fashion Boutique',
  logo_url text not null default '',
  hero_image_url text not null default '',
  description_cn text not null default '',
  description_en text not null default '',
  description_gr text not null default '',
  phone text not null default '',
  whatsapp text not null default '',
  instagram text not null default '',
  facebook text not null default '',
  tiktok text not null default '',
  address text not null default '',
  google_maps_url text not null default '',
  opening_hours text not null default '',
  footer_text text not null default '',
  enable_skroutz boolean not null default false,
  feed_min_stock integer not null default 1 check (feed_min_stock >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

drop trigger if exists settings_updated_at on public.business_settings;
create trigger settings_updated_at before update on public.business_settings
for each row execute function public.set_updated_at();

